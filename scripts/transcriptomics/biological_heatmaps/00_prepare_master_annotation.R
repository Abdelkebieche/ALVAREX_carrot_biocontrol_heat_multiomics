## 14. EXPRESSION MATRIX FOR maSigPro HEATMAPS: D0 + D2 + D4
## D0 = pre-treatment baseline only (3 columns/genotype)
##############################
mean_masig_expression <- function(genotype, masig_dir) {
  expr <- readRDS(file.path(masig_dir, "00_inputs", "expr_vst_after_MAD.rds"))
  meta <- read_csv_flexible(file.path(masig_dir, "00_inputs", "metadata_filtered.csv"))

  if (is.null(rownames(expr))) stop("maSigPro expression matrix has no gene rownames: ", genotype)
  meta$Sample <- sprintf("%04d", as.integer(as.character(meta$Sample)))
  keep <- meta$Sample %in% colnames(expr)
  meta <- meta[keep, , drop = FALSE]

  temp_levels <- c("T0", "T1", "T2")
  time_levels <- c("P1", "P2", "P3")

  out <- list()
  for (tt in temp_levels) {
    for (tm in time_levels) {

      ## -------------------------------------------------------------
      ## D0/P1 is PRE-TREATMENT.
      ## There is ONE baseline per temperature, not Control + Treated.
      ## The duplicated D0 used internally in maSigPro is a modelling
      ## device only and must never appear as a separate heatmap column.
      ## -------------------------------------------------------------
      if (tm == "P1") {
        samps <- meta$Sample[
          as.character(meta$Temperature) == tt &
          as.character(meta$Treatment) == "EAU" &
          as.character(meta$Sampling_time) == tm
        ]
        samps <- intersect(samps, colnames(expr))
        if (!length(samps)) next

        nm <- paste(
          genotype,
          normalise_temp_display(tt),
          "Baseline",
          normalise_time_display(tm),
          sep = "_"
        )
        out[[nm]] <- rowMeans(expr[, samps, drop = FALSE], na.rm = TRUE)

      } else {
        ## D2/P2 and D4/P3: Control and Treated are real conditions.
        for (tr in c("EAU", "SDP")) {
          samps <- meta$Sample[
            as.character(meta$Temperature) == tt &
            as.character(meta$Treatment) == tr &
            as.character(meta$Sampling_time) == tm
          ]
          samps <- intersect(samps, colnames(expr))
          if (!length(samps)) next

          nm <- paste(
            genotype,
            normalise_temp_display(tt),
            normalise_trt_display(tr),
            normalise_time_display(tm),
            sep = "_"
          )
          out[[nm]] <- rowMeans(expr[, samps, drop = FALSE], na.rm = TRUE)
        }
      }
    }
  }

  if (!length(out)) stop("No maSigPro heatmap conditions generated for ", genotype)

  mat <- do.call(cbind, out)
  rownames(mat) <- rownames(expr)
  as.data.frame(mat) |>
    tibble::rownames_to_column("Gene")
}

