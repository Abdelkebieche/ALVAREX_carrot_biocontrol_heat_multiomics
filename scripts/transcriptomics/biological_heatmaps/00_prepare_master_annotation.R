assert_file <- function(path, label = "file") {
  if (is.na(path) || !file.exists(path)) stop(label, " not found: ", path)
  invisible(path)
}

read_csv_flexible <- function(path) {
  assert_file(path, "Input file")
  x <- tryCatch(
    readr::read_csv(path, show_col_types = FALSE, progress = FALSE),
    error = function(e) NULL
  )
  if (is.null(x) || ncol(x) <= 1L) {
    x <- readr::read_delim(path, delim = ";", show_col_types = FALSE, progress = FALSE)
  }
  as.data.frame(x, stringsAsFactors = FALSE)
}

safe_read_csv <- function(path) {
  if (!file.exists(path)) return(data.frame())
  read_csv_flexible(path)
}

latest_matching_dir <- function(root, pattern, recursive = TRUE) {
  if (!dir.exists(root)) return(NA_character_)
  dd <- list.dirs(root, recursive = recursive, full.names = TRUE)
  hit <- dd[grepl(pattern, basename(dd))]
  if (!length(hit)) return(NA_character_)
  hit[order(file.info(hit)$mtime, decreasing = TRUE)][1]
}

latest_named_file <- function(roots, filename) {
  roots <- roots[dir.exists(roots)]
  if (!length(roots)) return(NA_character_)
  hits <- unlist(lapply(roots, function(root) {
    list.files(root, recursive = TRUE, full.names = TRUE, pattern = paste0("^", gsub("\\.", "\\\\.", filename), "$"))
  }), use.names = FALSE)
  hits <- hits[file.exists(hits)]
  if (!length(hits)) return(NA_character_)
  hits[order(file.info(hits)$mtime, decreasing = TRUE)][1]
}

find_masig_dir <- function(genotype) {
  exact <- file.path(MASIGPRO_ROOT, paste0(genotype, "_maSigPro"))
  if (dir.exists(exact)) return(exact)
  z <- latest_matching_dir(MASIGPRO_ROOT, paste0("^", genotype, "_maSigPro$"))
  if (!is.na(z)) return(z)
  latest_matching_dir(PROJECT_ROOT, paste0("^", genotype, "_maSigPro$"))
}

