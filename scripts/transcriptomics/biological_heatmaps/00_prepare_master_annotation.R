mean_wgcna_expression <- function(genotype, run_dir) {
  datExpr <- readRDS(file.path(run_dir, "02_network", "datExpr_clean.rds"))
  meta <- readRDS(file.path(run_dir, "02_network", "meta_clean.rds"))

  datExpr <- as.data.frame(datExpr)
  if (is.null(rownames(datExpr))) stop("datExpr has no sample rownames: ", run_dir)
  meta$Sample <- as.character(meta$Sample)
  idx <- match(rownames(datExpr), meta$Sample)
  if (anyNA(idx)) stop("Could not align datExpr with metadata for ", genotype)
  meta <- meta[idx, , drop = FALSE]

  temp <- normalise_temp_display(meta$Temperature)
  trt <- normalise_trt_display(meta$Treatment)
  tim <- normalise_time_display(meta$Sampling_time)
  group <- paste(genotype, temp, trt, tim, sep = "_")

  groups <- unique(group)
  means <- vapply(groups, function(g) {
    rows <- which(group == g)
    colMeans(datExpr[rows, , drop = FALSE], na.rm = TRUE)
  }, FUN.VALUE = numeric(ncol(datExpr)))

  rownames(means) <- colnames(datExpr)
  as.data.frame(means) |>
    tibble::rownames_to_column("Gene")
}

