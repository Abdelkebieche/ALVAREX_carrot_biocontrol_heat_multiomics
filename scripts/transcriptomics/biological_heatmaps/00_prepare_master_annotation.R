read_one_functional_family <- function(fam_dir) {
  folder <- file.path(FUNCTIONAL_INPUT_DIR, fam_dir)
  if (!dir.exists(folder)) return(data.frame())

  sf_file <- list.files(folder, full.names = TRUE, pattern = "_subfamily_assignment\\.csv$")
  pr_file <- list.files(folder, full.names = TRUE, pattern = "_KEGG_provenance\\.csv$")
  if (!length(sf_file) && !length(pr_file)) return(data.frame())

  sf <- if (length(sf_file)) read_csv_flexible(sf_file[1]) else data.frame()
  pr <- if (length(pr_file)) read_csv_flexible(pr_file[1]) else data.frame()

  sf2 <- if (nrow(sf)) {
    gcol <- first_existing_col(sf, c("Gene", "my_gene_id"))
    scol <- first_existing_col(sf, c("Subfamily", "subfamily"))
    if (!is.na(gcol)) {
      sf |>
        dplyr::transmute(
          Gene = clean_gene(.data[[gcol]]),
          Functional_subfamily_source = if (!is.na(scol)) as.character(.data[[scol]]) else NA_character_
        ) |>
        dplyr::distinct(Gene, .keep_all = TRUE)
    } else data.frame()
  } else data.frame()

  pr2 <- if (nrow(pr)) {
    gcol <- first_existing_col(pr, c("my_gene_id", "Gene"))
    if (!is.na(gcol)) {
      pr |>
        dplyr::mutate(Gene = clean_gene(.data[[gcol]])) |>
        dplyr::group_by(Gene) |>
        dplyr::summarise(
          Functional_KEGG_pathways = collapse_unique(if ("Pathway" %in% colnames(pr)) Pathway else character()),
          Functional_KEGG_pathway_num = collapse_unique(if ("pathway_num" %in% colnames(pr)) pathway_num else character()),
          Functional_annotation = collapse_unique(if ("func_clean" %in% colnames(pr)) func_clean else character()),
          .groups = "drop"
        )
    } else data.frame()
  } else data.frame()

  z <- full_join(sf2, pr2, by = "Gene")
  if (!nrow(z)) return(data.frame())
  z |>
    dplyr::mutate(
      Functional_family_ID = fam_dir,
      Functional_family = unname(FUNCTIONAL_FAMILY_LABELS[fam_dir])
    )
}

