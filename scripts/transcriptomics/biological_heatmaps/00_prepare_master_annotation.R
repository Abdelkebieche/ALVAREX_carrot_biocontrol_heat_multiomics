load_wgcna_gene_info <- function(genotype, run_dir) {
  gene_mod <- read_csv_flexible(file.path(run_dir, "02_network", "Gene_to_Module.csv")) |>
    dplyr::mutate(
      Gene = clean_gene(Gene),
      ModuleColor = as.character(ModuleColor)
    )

  hubs <- read_csv_flexible(file.path(run_dir, "04_hub_genes", "AllGenes_kME_GS.csv")) |>
    dplyr::mutate(
      Gene = clean_gene(Gene),
      ModuleColor = as.character(ModuleColor)
    )

  ## IMPORTANT: ModuleColor must be retained because the join uses Gene + ModuleColor.
  keep_hub <- intersect(
    c("Gene", "ModuleColor", "kME", "GS_Temperature", "GS_Treatment", "GS_Time",
      "IsHub", "IsHighGS_Temp", "IsHighGS_Trt"),
    colnames(hubs)
  )

  hub_small <- hubs |>
    dplyr::select(dplyr::all_of(keep_hub)) |>
    dplyr::distinct(Gene, ModuleColor, .keep_all = TRUE)

  out <- gene_mod |>
    dplyr::select(dplyr::any_of(c("Gene", "ModuleLabel", "ModuleColor"))) |>
    dplyr::distinct(Gene, ModuleColor, .keep_all = TRUE) |>
    dplyr::left_join(hub_small, by = c("Gene", "ModuleColor"))

  ## Create optional columns if an older WGCNA run did not export them.
  optional_numeric <- c("kME", "GS_Temperature", "GS_Treatment", "GS_Time")
  for (nm in optional_numeric) {
    if (!nm %in% colnames(out)) out[[nm]] <- NA_real_
  }
  optional_logical <- c("IsHub", "IsHighGS_Temp", "IsHighGS_Trt")
  for (nm in optional_logical) {
    if (!nm %in% colnames(out)) out[[nm]] <- NA
  }

  out <- out |>
    dplyr::mutate(
      Genotype = genotype,
      In_WGCNA = TRUE,
      kME = as.numeric(kME),
      GS_Temperature = as.numeric(GS_Temperature),
      GS_Treatment = as.numeric(GS_Treatment),
      GS_Time = as.numeric(GS_Time),
      WGCNA_DynamicHub = !is.na(kME) & kME >= KME_HUB_CUTOFF,
      WGCNA_TreatmentPriorityHub =
        WGCNA_DynamicHub & !is.na(GS_Treatment) & abs(GS_Treatment) >= GS_PRIORITY_CUTOFF
    )

  out
}

