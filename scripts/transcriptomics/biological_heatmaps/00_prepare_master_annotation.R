load_masig_info <- function(genotype, masig_dir) {
  cl <- read_csv_flexible(file.path(masig_dir, "04_tables", "Gene_cluster_assignment.csv")) |>
    dplyr::transmute(Gene = clean_gene(Gene), maSigPro_cluster = as.integer(Cluster))

  strict_file <- file.path(masig_dir, "04_tables", "maSigPro_strict_genes_Tfit.csv")
  strict <- if (file.exists(strict_file)) {
    read_csv_flexible(strict_file) |> dplyr::transmute(Gene = clean_gene(Gene), maSigPro_strict = TRUE)
  } else {
    data.frame(Gene = character(), maSigPro_strict = logical())
  }

  cl |>
    dplyr::left_join(strict, by = "Gene") |>
    dplyr::mutate(
      maSigPro_strict = tidyr::replace_na(maSigPro_strict, FALSE),
      In_maSigPro = TRUE,
      Genotype = genotype
    )
}

