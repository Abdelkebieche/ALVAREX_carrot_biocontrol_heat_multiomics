## MASTER INPUT BUILDER for biological heatmaps
##
## PURPOSE
##   Build one publication-oriented annotation/analysis master table that
##   connects the CURRENT WGCNA + maSigPro analyses with the biological
##   annotation logic used in the former scripts 09A / 09B / 09C / 10.
